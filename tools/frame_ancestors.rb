# Who may put embed.html in an iframe: the CSP frame-ancestors of the
# embedded cell (docs/HANDOVER.md §6k). A setting of the deploy, not of the
# code: the host's EMBED_FRAME_ANCESTORS (tools/embed_frame_ancestors.rb
# writes it into nginx/embed-frame-ancestors.inc), the dev server's
# FRAME_ANCESTORS (tools/dev_server.rb). Both read it here, in one format:
#
#   origins separated by spaces or commas, e.g.
#   "https://idogawa.com https://blog.example.org"
#
# Allowed: https://host (at least one dot; a port, or "*." in front of a
# name with two labels or more, as CSP has them), and for development only
# http://localhost, http://127.0.0.1 and http://<name>.test (with a port or
# ":*"). No paths, no quotes, no "*" alone, no other scheme - a typo cannot
# open the cells to every site or break the policy. Empty: DEFAULT.
module FrameAncestors
  DEFAULT = "https://idogawa.com"

  LABEL = "[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?"
  PORT = "(?::(?:[0-9]{1,5}|\\*))?"
  HTTPS = %r{\Ahttps://(?:\*\.#{LABEL}(?:\.#{LABEL})+|#{LABEL}(?:\.#{LABEL})+)#{PORT}\z}
  DEV = %r{\Ahttp://(?:localhost|127\.0\.0\.1|(?:\*\.)?(?:#{LABEL}\.)*#{LABEL}\.test)#{PORT}\z}

  class Invalid < ArgumentError; end

  module_function

  def valid?(origin) = HTTPS.match?(origin) || DEV.match?(origin)

  # the list as frame-ancestors takes it ("a b"), or Invalid naming what is wrong
  def parse(text)
    origins = text.to_s.downcase.split(/[\s,]+/).reject(&:empty?).uniq
    return DEFAULT if origins.empty?

    bad = origins.reject { |origin| valid?(origin) }
    raise Invalid, "not an allowed origin for frame-ancestors: #{bad.join(', ')}" unless bad.empty?

    origins.join(" ")
  end

  # nginx/embed-frame-ancestors.inc: included in nginx/default.conf's server
  # block after its default, so it wins
  def nginx_include(list)
    "# generated by tools/embed_frame_ancestors.rb from EMBED_FRAME_ANCESTORS - do not edit\n" \
      "set $chunky_embed_frame_ancestors \"#{parse(list)}\";\n"
  end
end
