// Writes site/embed-ui.js: the course's interface strings (lessons.js "ui"),
// without the 600 KB of lessons. The kernel (main.rb) formats gem errors,
// widget labels and loading notes from them; the embed shows "Run" and
// "Loading Ruby" from them too.
//
//   node experiments/09-embed-cell/build_embed_ui.mjs
//
// lessons.js is a script (window.LESSONS_JSON = JSON.stringify({...})), so
// it runs in a bare vm context with a stand-in window.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, "../../html/lessons.js"), "utf8");
const context = { window: {} };
vm.runInNewContext(source, context, { filename: "lessons.js" });
const ui = JSON.parse(context.window.LESSONS_JSON).ui;

const out = "// generated by build_embed_ui.mjs from html/lessons.js - do not edit\n" +
  "window.CHUNKY_EMBED_UI = " + JSON.stringify(ui) + ";\n";
writeFileSync(join(here, "site/embed-ui.js"), out);
console.log(`site/embed-ui.js: ${Object.keys(ui).join(", ")}, ${out.length} bytes`);
